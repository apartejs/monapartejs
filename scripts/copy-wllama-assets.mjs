/**
 * Copy wllama's .wasm and its compat build into `public/assets/` before a build or a serve.
 *
 * Same reason as copy-titler-model.mjs: an `assets` glob into node_modules follows pnpm's
 * symlinks on Windows and copies NOTHING on Linux, where the image is built. The engine
 * must find these files on our own origin — never a CDN: nothing leaves the device, and
 * the app must start offline.
 *  - `wllama/<hash>/wllama.wasm`: the build every recent Chromium runs (JSPI + Memory64);
 *  - `wllama-compat/<hash>/`: what wllama switches to without them (Safari). Left to its
 *    default, wllama would fetch it from jsDelivr.
 *
 * Each folder is named after its files' content (the start of their sha256), and the paths are
 * written to src/app/souffleurs/engine/wllama-assets.ts for the engine. Under one fixed URL, the
 * service worker served the previous deployment's .wasm to the new page (it caches the .wasm and
 * fetches pages from the network first): "Invalid typed array length: 1163217991" — the glue's
 * bytes "GLUE" read as a length — until the user clicked the update button (6/11).
 */
import { createHash } from 'node:crypto';
import { copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { basename, join } from 'node:path';

const require = createRequire(import.meta.url);

const sets = {
  wasm: { folder: 'wllama', files: ['@wllama/wllama/esm/wasm/wllama.wasm'] },
  compat: {
    folder: 'wllama-compat',
    files: ['@wllama/wllama-compat/wasm/wllama.wasm', '@wllama/wllama-compat/wasm/wllama.js'],
  },
};

const urls = {};
for (const [key, { folder, files }] of Object.entries(sets)) {
  const sources = files.map((specifier) => require.resolve(specifier));
  const hash = createHash('sha256');
  for (const source of sources) hash.update(readFileSync(source));
  const dir = hash.digest('hex').slice(0, 12);
  // Generated and gitignored: an older build's folder must not ship beside this one.
  rmSync(join('public', 'assets', folder), { recursive: true, force: true });
  const directory = join('public', 'assets', folder, dir);
  mkdirSync(directory, { recursive: true });
  for (const source of sources) {
    copyFileSync(source, join(directory, basename(source)));
    console.log(`[wllama] ${source} -> ${join(directory, basename(source))}`);
  }
  urls[key] = Object.fromEntries(
    sources.map((s) => [basename(s), `/assets/${folder}/${dir}/${basename(s)}`]),
  );
}

const generated = `// Generated by scripts/copy-wllama-assets.mjs before every build and serve: the folders are named after their
// files' content, so a page never runs a .wasm cached from another deployment. Commit it when it changes.
export const WLLAMA_ASSETS = {
  wasm: '${urls.wasm['wllama.wasm']}',
  compatWasm: '${urls.compat['wllama.wasm']}',
  compatWorker: '${urls.compat['wllama.js']}',
} as const;
`;
writeFileSync(join('src', 'app', 'souffleurs', 'engine', 'wllama-assets.ts'), generated);
console.log('[wllama] src/app/souffleurs/engine/wllama-assets.ts written');
